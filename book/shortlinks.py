"""Short links for Elements of Data Science: greenteapress.com/eds/N.

links.csv is the catalog. Numbers are permanent: never reuse or renumber;
to fix a dead link, change its target. emit.py rewrites the external links
in the PDF and EPUB to these; the notebooks and the website keep the direct
URLs. Same scheme as The Little Book of Semaphores (GreenTeaPress Task 12).

usage:
  python book/shortlinks.py update           # add links the book uses that aren't in links.csv
  python book/shortlinks.py check            # every link the book uses is in links.csv
  python book/shortlinks.py htaccess [PATH]  # write the redirects (default:
                                             # ~/GreenTeaPress/greenteapress/eds/.htaccess)

Run update after book/stage.py, since it reads the staged notebooks. Then
deploy from ~/GreenTeaPress: commit, and scripts/deploy_gtp.sh eds
"""

import csv
import sys
import tempfile
from pathlib import Path

from emit import (BOOK, LINKS, Emitter, all_chapters, chapter_numbers,
                  load_links, load_metadata)

CODE = "eds"
HOME = "https://greenteapress.com/wp/elements-of-data-science/"
DEFAULT = Path.home() / "GreenTeaPress" / "greenteapress" / CODE / ".htaccess"
FRONT = ["preface", "book_back", "sample_back"]


def used_links():
    """Every external link in the book, in reading order: (url, where)."""
    meta = load_metadata()
    numbers = chapter_numbers(meta)
    with tempfile.TemporaryDirectory() as tmp:
        emitter = Emitter("epub", Path(tmp), meta)
        emitter.short_links("preface", 0, (BOOK / "front" / "preface.md").read_text())
        for stem in all_chapters(meta):
            emitter.chapter(stem, numbers.get(stem))
        for name in FRONT[1:]:
            emitter.short_links(name, 0, (BOOK / "front" / f"{name}.md").read_text())
    first = {}
    for url, where in emitter.seen:
        first.setdefault(url, where)
    return list(first.items())


def load_rows():
    if not LINKS.exists():
        return []
    with open(LINKS, newline="") as f:
        rows = [(int(r["n"]), r["target"], r["note"]) for r in csv.DictReader(f)]
    ns = [n for n, _, _ in rows]
    assert ns == sorted(set(ns)), "link numbers must be unique and in order"
    return rows


def update():
    rows = load_rows()
    known = load_links()
    added = 0
    for url, where in used_links():
        if url not in known:
            n = rows[-1][0] + 1 if rows else 1
            rows.append((n, url, where))
            known[url] = n
            added += 1
    with open(LINKS, "w", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(["n", "target", "note"])
        writer.writerows(rows)
    print(f"{added} added; {len(rows)} in links.csv")


def check():
    known = load_links()
    used = dict(used_links())
    missing = [url for url in used if url not in known]
    for url in missing:
        print(f"not in links.csv: {url} ({used[url]})")
    for url in known:
        if url not in used:
            print(f"in links.csv but not used (fine if retired): {url}")
    print(f"{len(used)} links used, {len(known)} in links.csv")
    return not missing


def htaccess(path=DEFAULT):
    path = Path(path)
    lines = [f"# Short links for Elements of Data Science: greenteapress.com/{CODE}/N",
             "# Generated by ElementsOfDataScience/book/shortlinks.py from "
             "book/links.csv. Do not edit here.",
             f"RedirectMatch 302 ^/{CODE}/?$ {HOME}"]
    for n, target, note in load_rows():
        lines.append(f"# {note}")
        lines.append(f"RedirectMatch 302 ^/{CODE}/{n}/?$ {target}")
    lines.append("# Unknown numbers go to the book page")
    lines.append(f"RedirectMatch 302 ^/{CODE}/.+$ {HOME}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "update":
        update()
    elif cmd == "check":
        sys.exit(0 if check() else 1)
    elif cmd == "htaccess":
        htaccess(*sys.argv[2:3])
    else:
        sys.exit(__doc__)
